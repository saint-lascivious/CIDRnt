#!/bin/sh

# CIDRnt-groups-map-gen.sh - Generate CIDRnt groups map from the locales map.
#
# Emits three kinds of groups:
#   - RIR groups, derived from the locale|RIR entries in the locales map
#   - curated groups (eu, efta, ...), defined in CURATED below
#   - user groups, preserved verbatim from the existing groups map
#
# Managed groups (RIR + curated) are regenerated; hand-edits to them in
# the groups map are lost. Edit the curated definitions here instead.

set -eu

LOCALES_MAP="${1:-./resources/locales_map/locales.map}"
GROUPS_MAP="${2:-./resources/groups_map/groups.map}"
TMP=$(mktemp -d)

trap 'rm -rf "$TMP"' EXIT

MANAGED_GROUPS="afrinic apnic arin lacnic ripencc africa apac efta eu europe five-eyes latam north-america"

CURATED=$(cat <<'EOF'
africa|AO,BF,BI,BJ,BW,CD,CF,CG,CI,CM,CV,DJ,DZ,EG,ER,ET,GA,GH,GM,GN,GQ,GW,KE,KM,LR,LS,LY,MA,MG,ML,MR,MU,MW,MZ,NA,NE,NG,RE,RW,SC,SD,SL,SN,SO,SS,ST,SZ,TD,TG,TN,TZ,UG,YT,ZA,ZM,ZW
apac|AS,AU,BD,BN,BT,CK,CN,FJ,FM,GU,HK,ID,IN,IO,JP,KH,KI,KP,KR,LA,LK,MH,MM,MN,MO,MP,MV,MY,NC,NF,NP,NR,NU,NZ,PF,PG,PH,PK,PW,SB,SG,TH,TK,TL,TO,TV,TW,VN,VU,WF,WS
efta|CH,IS,LI,NO
eu|AT,BE,BG,CY,CZ,DE,DK,EE,ES,FI,FR,GR,HR,HU,IE,IT,LT,LU,LV,MT,NL,PL,PT,RO,SE,SI,SK
europe|AD,AL,AM,AT,AX,AZ,BA,BE,BG,BY,CH,CY,CZ,DE,DK,EE,ES,FI,FO,FR,GB,GE,GG,GI,GR,HR,HU,IE,IL,IM,IS,IT,JE,LI,LT,LU,LV,MC,MD,ME,MK,MT,NL,NO,PL,PT,RO,RS,RU,SE,SI,SK,SM,TR,UA,VA
five-eyes|AU,CA,GB,NZ,US
latam|AR,AW,BO,BQ,BR,BZ,CL,CO,CR,CU,CW,DO,EC,GF,GT,GY,HN,HT,MX,NI,PA,PE,PY,SR,SV,SX,TT,UY,VE
north-america|AG,AI,BB,BL,BM,BS,CA,DM,GD,GP,JM,KN,KY,LC,MF,MS,PM,PR,TC,US,VC,VG,VI
EOF
)

# shellcheck disable=SC2086
EXCLUDE_RE=$(printf '%s\n' $MANAGED_GROUPS \
    | awk '{ printf "%s%s", (NR > 1 ? "|" : ""), $0 }')

if [ ! -f "$LOCALES_MAP" ]; then

    printf 'error: locales map not found: %s\n' "$LOCALES_MAP" >&2
    printf 'run scripts/CIDRnt-locales-map-gen.sh first\n' >&2
    exit 1

fi

mkdir -p "$(dirname "$GROUPS_MAP")"

{
    printf '# Generated by %s\n\n' "$(basename "$0")"
    printf '# This file maps locale group names to ISO-3166 alpha-2 locales\n\n'
    printf '# Group names: lowercase letters, digits, '"'"'-'"'"' and '"'"'_'"'"' (case-insensitive match)\n'
    printf '# Referenced on the command line as @group, e.g. ./CIDRnt @mygroup\n\n'
    printf '# Locales are ISO-3166 alpha-2 codes. To list all known locales, run:\n'
    printf '# ./CIDRnt -L          (or -L N to list only locales starting with N)\n\n'
    printf '# The RIR groups below are derived from the locales map. The curated\n'
    printf '# groups (africa, apac, efta, eu, europe, five-eyes, latam,\n'
    printf '# north-america) are defined in the generator script. Both kinds are\n'
    printf '# regenerated, so hand-edits to them are lost.\n\n'
    printf '# Any other groups you add by hand will survive regeneration.\n\n'
    printf '# Format: group|locale,locale,...\n\n'
    printf '# Example:\n'
    printf '# mygroup|NZ,AU,JP\n'
    printf '# pacific-islands|FJ,WS,TO,VU\n\n'

    if [ -f "$GROUPS_MAP" ]; then

        grep -Ev "^($EXCLUDE_RE)\|" "$GROUPS_MAP" \
            | grep -Ev '^(#|[[:space:]]*$)' || true

    fi

    printf '%s\n' "$CURATED"

    awk -F'|' '/^[A-Z][A-Z]\|/ {
        a[$2] = a[$2] (a[$2] ? "," : "") $1
    } END {
        for (r in a) print r "|" a[r]
    }' "$LOCALES_MAP" | sort

} > "$TMP/groups"

mv "$TMP/groups" "$GROUPS_MAP"

printf 'RIR locale groups generated in %s\n' "$GROUPS_MAP"
